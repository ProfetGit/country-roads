package io.github.profetgit.countryroads.dev;

import io.github.profetgit.countryroads.CountryRoads;
import io.github.profetgit.countryroads.world.RoadColumns;
import it.unimi.dsi.fastutil.longs.LongOpenHashSet;
import net.minecraft.commands.CommandSourceStack;
import net.minecraft.core.BlockPos;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.tags.BlockTags;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.chunk.LevelChunk;
import net.minecraft.world.level.chunk.status.ChunkStatus;

/**
 * bamboo R: the chunks of a world that already exist, as saved (road columns from the saved attachment, nothing replanned):
 * bamboo within NEAR blocks of a road column, and how much of it has nothing it can grow on under its base. Chunks that
 * were never generated are generated by the usual rules and have no saved roads.
 */
final class SavedScan {
    static final int NEAR = 14;

    private SavedScan() {}

    static int bamboo(CommandSourceStack src, int radius) {
        ServerLevel level = src.getLevel();
        BlockPos at = BlockPos.containing(src.getPosition());
        int r = radius >> 4, cx0 = (at.getX() >> 4) - r, cz0 = (at.getZ() >> 4) - r, side = 2 * r + 1, total = side * side;
        int[] next = {0};
        LongOpenHashSet roads = new LongOpenHashSet();
        long[] count = {0, 0, 0};
        int[] pass = {0};
        StringBuilder ex = new StringBuilder();
        DevCommands.queue(() -> {
            long until = System.nanoTime() + 40_000_000L;
            while (next[0] < total && System.nanoTime() < until) {
                int i = next[0]++, cx = cx0 + i % side, cz = cz0 + i / side;
                LevelChunk c = (LevelChunk) level.getChunkSource().getChunk(cx, cz, ChunkStatus.FULL, true);
                if (pass[0] == 0) {
                    for (int dx = 0; dx < 16; dx++)
                        for (int dz = 0; dz < 16; dz++)
                            if (RoadColumns.isRoad(level, (cx << 4) + dx, (cz << 4) + dz)) roads.add(ChunkPos.pack((cx << 4) + dx, (cz << 4) + dz));
                } else {
                    BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
                    for (int dx = 0; dx < 16; dx++)
                        for (int dz = 0; dz < 16; dz++) {
                            int x = (cx << 4) + dx, z = (cz << 4) + dz;
                            boolean near = false;
                            for (int ox = -NEAR; ox <= NEAR && !near; ox += 2)
                                for (int oz = -NEAR; oz <= NEAR && !near; oz += 2) near = roads.contains(ChunkPos.pack(x + ox, z + oz));
                            if (!near) continue;
                            for (int y = level.getMinY(); y < level.getMaxY(); y++) {
                                BlockState s = c.getBlockState(p.set(x, y, z));
                                if (!s.is(Blocks.BAMBOO)) continue;
                                BlockState under = c.getBlockState(p.set(x, y - 1, z));
                                if (under.is(Blocks.BAMBOO)) continue;
                                count[0]++;
                                if (!under.is(BlockTags.SUPPORTS_BAMBOO)) {
                                    count[1]++;
                                    if (ex.length() < 400) ex.append(x).append(',').append(y).append(',').append(z).append('/').append(under.getBlock().getDescriptionId().replace("block.minecraft.", "")).append(' ');
                                }
                            }
                        }
                }
            }
            if (next[0] < total) return false;
            if (pass[0] == 0) {
                pass[0] = 1;
                next[0] = 0;
                return false;
            }
            String line = "CR-SAVEDBAMBOO r=" + radius + " roadColumns=" + roads.size() + " stalksNearRoad=" + count[0] + " floating=" + count[1] + " examples=[" + ex + "]";
            CountryRoads.LOG.info(line);
            src.sendSuccess(() -> Component.literal(line), false);
            return true;
        });
        return 1;
    }
}
